// Generates the static project map (NW Europe) used on the projects page.
import { writeFileSync, readFileSync } from "node:fs";
import { geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/countries-50m.json", "utf8"));
const countries = feature(topo, topo.objects.countries);
const W = 800, H = 640;
const bbox = { type: "Feature", geometry: { type: "MultiPoint", coordinates: [[-10.8, 50.2], [12.5, 50.2], [12.5, 58.9], [-10.8, 58.9]] } };
const projection = geoMercator().fitExtent([[0, 0], [W, H]], bbox);
const path = geoPath(projection);
const keep = new Set(["United Kingdom", "Ireland", "Netherlands", "Belgium", "Germany", "Denmark", "France", "Luxembourg", "Norway", "Sweden", "Isle of Man"]);
const shapes = countries.features
  .filter((f) => keep.has(f.properties.name))
  .map((f) => ({ name: f.properties.name, d: path(f) }))
  .filter((s) => s.d);
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n))));
const k = projection.scale(), [tx, ty] = projection.translate();
const out = `// Generated by scripts/build-map.mjs. Do not edit by hand.
export const mapSize = { w: ${W}, h: ${H} };
export const mapProjection = { k: ${k.toFixed(4)}, tx: ${tx.toFixed(4)}, ty: ${ty.toFixed(4)} };
export const mapShapes: { name: string; d: string }[] = ${JSON.stringify(shapes.map((s) => ({ name: s.name, d: round(s.d) })))};
`;
writeFileSync("src/content/map-data.ts", out);
console.log("map shapes:", shapes.length, "bytes:", out.length);
